window.i18n = {
  currentLang: localStorage.getItem('bondihora_lang') || 'es',
  
  setLang(lang) {
    if (translations[lang]) {
      this.currentLang = lang;
      localStorage.setItem('bondihora_lang', lang);
      this.applyTranslations();
      // Dispatch an event so other scripts can react if needed
      window.dispatchEvent(new Event('languageChanged'));
    }
  },
  
  get(key) {
    return translations[this.currentLang][key] || translations['es'][key] || key;
  },
  
  applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (key && this.get(key)) {
        if (el.tagName === 'INPUT' && el.type === 'placeholder') {
          el.placeholder = this.get(key);
        } else {
          el.childNodes.forEach(node => {
            if (node.nodeType === Node.TEXT_NODE && node.textContent.trim().length > 0) {
                node.textContent = this.get(key);
            }
          });
          if (el.childNodes.length === 0) {
              el.textContent = this.get(key);
          }
        }
      }
    });
  }
};
